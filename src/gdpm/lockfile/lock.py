"""
锁文件读写, 提供 gdpm.lock (TOML 格式) 的解析与生成.

----

example:
    锁文件结构:

        version = 1

        [[package]]
        name = "limbo-ai"
        version = "1.2.0"
        source = "github"

----

Note:
    - read_lockfile: 解析锁文件为 LockEntry 列表.
    - write_lockfile: 将 LockEntry 列表写回锁文件.
    - find_lockfile: 定位项目根目录下的 gdpm.lock.
"""

from __future__ import annotations

import tomllib
from typing import TYPE_CHECKING, Any

from gdpm.models.lock import LockEntry

if TYPE_CHECKING:
    from pathlib import Path


def read_lockfile(path: Path) -> list[LockEntry]:
    """
    读取锁文件, 文件不存在时返回空列表.

    ----

    Args:
        path: gdpm.lock 的路径.

    Returns:
        锁文件中的 LockEntry 列表.
    """
    if not path.exists():
        return []

    with open(path, "rb") as f:
        data: dict[str, Any] = tomllib.load(f)

    entries: list[LockEntry] = []
    for pkg in data.get("package", []):
        entries.append(
            LockEntry(
                name=pkg.get("name", ""),
                version=pkg.get("version", ""),
                source=pkg.get("source", ""),
            )
        )
    return entries


def write_lockfile(entries: list[LockEntry], path: Path) -> None:
    """
    写入锁文件, 条目按名称排序, 生成的文件为 gdpm 自动生成, 不应手工编辑.

    ----

    Args:
        entries: 要写入的锁文件条目.
        path: gdpm.lock 的路径.
    """
    lines: list[str] = []
    lines.append("# This file is auto-generated by gdpm. Do not edit manually.")
    lines.append("version = 1")
    lines.append("")

    for entry in sorted(entries, key=lambda e: e.name):
        lines.append("[[package]]")
        lines.append(f'name = "{entry.name}"')
        lines.append(f'version = "{entry.version}"')
        lines.append(f'source = "{entry.source}"')
        lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")


def find_lockfile(project_root: Path) -> Path:
    """
    定位锁文件路径.

    ----

    Args:
        project_root: 项目根目录.

    Returns:
        项目根目录下的 gdpm.lock 路径.
    """
    return project_root / "gdpm.lock"
