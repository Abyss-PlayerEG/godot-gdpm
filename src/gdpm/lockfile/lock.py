"""
锁文件读写, 提供 gdpm.lock (TOML 格式) 的解析与生成.

Lock file read and write. Provide parsing and generation of gdpm.lock
(TOML format).

----

example:
    锁文件结构 / Lock file layout:

        version = 1

        [[package]]
        name = "limbo-ai"
        version = "1.2.0"
        source = "github"

----

Note:
    - read_lockfile: 解析锁文件为 LockEntry 列表 /
        Parse the lock file into a list of LockEntry.
    - write_lockfile: 将 LockEntry 列表写回锁文件 /
        Write a list of LockEntry back to the lock file.
    - find_lockfile: 定位项目根目录下的 gdpm.lock /
        Locate gdpm.lock under the project root.
"""

from __future__ import annotations

import tomllib
from typing import TYPE_CHECKING, Any

from gdpm.models.lock import LockEntry

if TYPE_CHECKING:
    from pathlib import Path


def read_lockfile(path: Path) -> list[LockEntry]:
    """
    读取锁文件, 文件不存在时返回空列表.

    Read the lock file. Return an empty list when the file is missing.

    ----

    Args:
        path: gdpm.lock 的路径 / Path to gdpm.lock.

    Returns:
        锁文件中的 LockEntry 列表 /
            List of LockEntry found in the lock file.
    """
    if not path.exists():
        return []

    with open(path, "rb") as f:
        data: dict[str, Any] = tomllib.load(f)

    entries: list[LockEntry] = []
    for pkg in data.get("package", []):
        entries.append(
            LockEntry(
                name=pkg.get("name", ""),
                version=pkg.get("version", ""),
                source=pkg.get("source", ""),
            )
        )
    return entries


def write_lockfile(entries: list[LockEntry], path: Path) -> None:
    """
    写入锁文件, 条目按名称排序, 生成的文件为 gdpm 自动生成, 不应手工编辑.

    Write the lock file. Entries are sorted by name; the generated file
    is auto-generated by gdpm and should not be edited manually.

    ----

    Args:
        entries: 要写入的锁文件条目 / Lock file entries to write.
        path: gdpm.lock 的路径 / Path to gdpm.lock.
    """
    lines: list[str] = []
    lines.append("# This file is auto-generated by gdpm. Do not edit manually.")
    lines.append("version = 1")
    lines.append("")

    for entry in sorted(entries, key=lambda e: e.name):
        lines.append("[[package]]")
        lines.append(f'name = "{entry.name}"')
        lines.append(f'version = "{entry.version}"')
        lines.append(f'source = "{entry.source}"')
        lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")


def find_lockfile(project_root: Path) -> Path:
    """
    定位锁文件路径.

    Find the lock file path.

    ----

    Args:
        project_root: 项目根目录 / Project root directory.

    Returns:
        项目根目录下的 gdpm.lock 路径 /
            Path to gdpm.lock under the project root.
    """
    return project_root / "gdpm.lock"
