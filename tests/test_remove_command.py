"""
gdpm remove 命令测试.

- tag 身份解析: 目录名与 slug 不同时仍能删除 (回归: 解压 zip 自带文件夹名).
- 目录缺失: 依赖照常解绑但如实提示磁盘未动.
- 直接目录名: 兼容无 tag 的老布局.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from click.testing import CliRunner

from gdpm.cli.commands.remove import remove

if TYPE_CHECKING:
    from pathlib import Path


def _make_project(tmp_path: Path, monkeypatch) -> None:
    monkeypatch.chdir(tmp_path)
    (tmp_path / "gdproject.toml").write_text(
        "[project]\n"
        'name = "demo"\n'
        'version = "0.1.0"\n'
        'godot = ">=4.0"\n'
        'license = "MIT"\n'
        'addons_dir = "addons"\n'
        "\n"
        "[dependencies]\n"
        'human-skeleton-2d = { version = "1.1.3", publisher = "renevanderark" }\n',
        encoding="utf-8",
    )
    (tmp_path / "gdpm.lock").write_text(
        "# This file is auto-generated by gdpm. Do not edit manually.\n"
        "version = 1\n"
        "\n"
        "[[package]]\n"
        'name = "human-skeleton-2d"\n'
        'version = "1.1.3"\n'
        'source = "store+renevanderark/human-skeleton-2d"\n',
        encoding="utf-8",
    )


def test_remove_deletes_dir_matched_by_tag(tmp_path: Path, monkeypatch) -> None:
    """目录名与 slug 不同时, 按 tag.gdpm 身份定位并删除."""
    _make_project(tmp_path, monkeypatch)
    addon = tmp_path / "addons" / "skeleleton-2d-asset"
    addon.mkdir(parents=True)
    (addon / "tag.gdpm").write_text(
        "store+renevanderark/human-skeleton-2d", encoding="utf-8"
    )
    (addon / "human_skeleton_2d.tscn").write_text("[gd_scene]", encoding="utf-8")

    result = CliRunner().invoke(remove, ["-y", "renevanderark/human-skeleton-2d"])

    assert result.exit_code == 0, result.output
    assert "Removed" in result.output
    assert not addon.exists()
    assert "human-skeleton-2d" not in (tmp_path / "gdproject.toml").read_text(
        encoding="utf-8"
    )
    assert "human-skeleton-2d" not in (tmp_path / "gdpm.lock").read_text(
        encoding="utf-8"
    )
    assert "No addons/ directory matched" not in result.output


def test_remove_notes_missing_directory(tmp_path: Path, monkeypatch) -> None:
    """目录已不存在时依赖照常解绑, 且如实提示磁盘未动."""
    _make_project(tmp_path, monkeypatch)

    result = CliRunner().invoke(remove, ["-y", "human-skeleton-2d"])

    assert result.exit_code == 0, result.output
    assert "Removed" in result.output
    assert "No addons/ directory matched" in result.output
    assert "human-skeleton-2d" not in (tmp_path / "gdproject.toml").read_text(
        encoding="utf-8"
    )


def test_remove_matches_direct_directory_name(tmp_path: Path, monkeypatch) -> None:
    """目录名 == slug (无 tag) 的老布局仍按直接目录名删除."""
    _make_project(tmp_path, monkeypatch)
    addon = tmp_path / "addons" / "human-skeleton-2d"
    addon.mkdir(parents=True)
    (addon / "plugin.cfg").write_text('[plugin]\nname = "x"\n', encoding="utf-8")

    result = CliRunner().invoke(remove, ["-y", "human-skeleton-2d"])

    assert result.exit_code == 0, result.output
    assert not addon.exists()
    assert "No addons/ directory matched" not in result.output
